/** Создаёт новые экземпляры демо-заметок с уникальными id и текущими датами. */
export function createSeedNotes(): Note[] {
  const now = Date.now();
  return SEED.map((n, i) => ({
    ...n,
    id: createId(),
    // Разные даты, чтобы «Недавние» на стартовой странице выглядели естественно.
    createdAt: new Date(now - (SEED.length - i) * 3600_000).toISOString(),
    updatedAt: new Date(now - (SEED.length - i) * 3600_000).toISOString(),
  }));
}
