// Модели карточек для интервального повторения слов (алгоритм SM-2).

/**
 * Карточка, извлечённая из заметки.
 * В Markdown записывается строкой `слово :: перевод`.
 */
export interface Flashcard {
  /** Стабильный идентификатор: хэш заметки + лицевой стороны. */
  id: string;
  /** Заметка-источник. */
  noteId: string;
  /** Лицевая сторона (слово на изучаемом языке). */
  front: string;
  /** Оборотная сторона (перевод / объяснение). */
  back: string;
  /** Теги заметки — используются как «колоды». */
  tags: string[];
}

/** Прогресс изучения карточки по алгоритму SM-2. */
export interface CardProgress {
  /** Идентификатор карточки. */
  cardId: string;
  /** Коэффициент лёгкости (EF), минимум 1.3. */
  ease: number;
  /** Текущий интервал в днях. */
  interval: number;
  /** Количество успешных повторений подряд. */
  repetitions: number;
  /** Дата следующего повторения (ISO). */
  due: string;
  /** Дата последнего повторения (ISO) или null. */
  lastReviewed: string | null;
}

/** Оценка ответа пользователем при повторении. */
export type ReviewGrade = 'again' | 'hard' | 'good' | 'easy';
